/**
 * 走查断言。
 *
 * `guitest.cjs` 只负责**把界面读出来**，判定放在这里。
 * 分开的理由：读数据的代码与"期望值"是两件会各自变化的事 ——
 * 混在一起改一个期望值要动那一大段读 DOM 的代码，容易改错。
 *
 * 用法：node scripts/guiassert.mjs        （读 _gui.json）
 *
 * ── 基准数字从哪来 ──
 * 断言里**尽量不写死条数**：夹具变了（`scripts/guidb.mjs` 改了演示数据）
 * 那些数字就得跟着改，而"忘了改"会表现成一堆看不懂的失败。
 * 所以先读 `30_明细_结构` 的行数当基准，其余断言与它比较 ——
 * "计数与列表不一致"这类真问题照样能抓到。
 */
import { readFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const FILE = join(ROOT, '_gui.json');

if (!existsSync(FILE)) {
  console.error('找不到 _gui.json —— 先跑 npm run test:gui');
  process.exit(2);
}
const G = JSON.parse(readFileSync(FILE, 'utf8'));

let pass = 0;
const fails = [];

function ok(cond, label, actual) {
  if (cond) {
    pass += 1;
    return;
  }
  fails.push(`${label}${actual === undefined ? '' : `（实际：${JSON.stringify(actual)}）`}`);
}
/** 取值；这一步失败过就返回 undefined，避免断言层再炸一次 */
function g(step) {
  const v = G[step];
  if (!v || v.__failed) return undefined;
  return v;
}

// 基准：明细页实际列出的行数
const N = (g('30_明细_结构') || {}).行数 ?? 0;

// ─── 总体 ───

ok((G.failed ?? []).length === 0, '走查没有失败步骤', G.failed);
ok(G.timeout !== true, '走查没有整轮超时', G.stuckAt);
ok((G.consoleErrors ?? []).length === 0, '渲染层没有 console 错误', G.consoleErrors);
ok(N > 0, '明细页有数据（基准行数 > 0）', N);

